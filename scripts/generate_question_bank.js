function idFor(index) {
  return 'c' + String(index).padStart(3, '0')
}

function difficultyFor(chapter, index) {
  if (chapter.indexOf('未定义行为') !== -1) {
    return index % 3 === 0 ? '面试' : '易错'
  }

  if (chapter.indexOf('面试') !== -1) {
    return index % 4 === 0 ? '易错' : '面试'
  }

  if (chapter.indexOf('数据结构') !== -1 || chapter.indexOf('排序') !== -1) {
    return ['基础', '进阶', '易错', '进阶'][index % 4]
  }

  return ['基础', '进阶', '易错', '面试'][index % 4]
}

function pickWrongOptions(spec, index) {
  const source = spec.wrong.concat(commonWrongOptions)
  const result = []
  let offset = index % source.length

  while (result.length < 3) {
    const value = source[offset % source.length]

    if (value !== spec.correct && result.indexOf(value) === -1) {
      result.push(value)
    }
    offset += 1
  }

  return result
}

function buildQuestion(chapter, localIndex, globalId) {
  const topicIndex = localIndex % chapter.topics.length
  const repeatIndex = Math.floor(localIndex / chapter.topics.length)
  const spec = chapter.topics[topicIndex]
  const promptIndex = (topicIndex * 13 + repeatIndex * 7 + chapter.topics.length) % promptTemplates.length
  const prompt = promptTemplates[promptIndex].replace('{topic}', spec.name)
  const wrongOptions = pickWrongOptions(spec, localIndex)
  const answer = globalId % 4
  const options = wrongOptions.slice()
  const explanationTailIndex = (topicIndex * 5 + repeatIndex * 7 + chapter.topics.length) % explanationTails.length
  let explanation = '围绕「' + spec.name + '」：' + spec.why + ' ' + explanationTails[explanationTailIndex]

  if (explanation.length < 55) {
    explanation += ' 审题时还要结合容量、边界条件和失败路径，不能只看一次运行结果。'
  }

  options.splice(answer, 0, spec.correct)

  return {
    id: idFor(globalId),
    chapter: chapter.chapter,
    topic: spec.name,
    difficulty: difficultyFor(chapter.chapter, localIndex),
    question: prompt,
    options: options,
    answer: answer,
    explanation: explanation,
    tags: spec.tags.concat(['扩展题库'])
  }
}

function writeChapterFile(chapter, questions) {
  const filePath = path.join(chapterDir, chapter.file + '.js')
  const content = 'module.exports = ' + JSON.stringify(questions, null, 2) + '\n'

  fs.writeFileSync(filePath, content, 'utf8')
}

function writeQuestionEntry() {
  const lines = []
  const names = []

  baseFiles.forEach(function (item) {
    lines.push("const " + item.name + " = require('./chapters/" + item.file + "')")
    names.push(item.name)
  })

  chapters.forEach(function (item) {
    lines.push("const " + item.varName + " = require('./chapters/" + item.file + "')")
    names.push(item.varName)
  })

  lines.push('')
  lines.push('const questions = []')
  names.forEach(function (name) {
    lines.push('  .concat(' + name + ')')
  })
  lines.push('')
  lines.push('module.exports = questions')

  fs.writeFileSync(questionEntryPath, lines.join('\n') + '\n', 'utf8')
}

function run() {
  let nextId = 34
  let generatedCount = 0

  if (!fs.existsSync(chapterDir)) {
    fs.mkdirSync(chapterDir, { recursive: true })
  }

  chapters.forEach(function (chapter) {
    const list = []

    for (let i = 0; i < chapter.target; i += 1) {
      list.push(buildQuestion(chapter, i, nextId))
      nextId += 1
    }

    generatedCount += list.length
    writeChapterFile(chapter, list)
  })

  writeQuestionEntry()
  console.log('已生成扩展题 ' + generatedCount + ' 道，预计总题数 1000 道。')
}

run()
