function topic(name, correct, why, wrong, tags) {
  return {
    name: name,
    correct: correct,
    why: why,
    wrong: wrong,
    tags: tags
  }
}

function makeTopics(rows) {
  return rows.map(function (row) {
    return topic(row[0], row[1], row[2], row[3], row[4])
  })
}

